"""Update the phrases of the hand-kept anchors.yaml files (no generator header,
so they may hold hand edits and are not regenerated) where an English
correction touched the words an anchor points at.

Each entry's phrase is located in the OLD prose the way stage1_archive's
_find_phrase does (the full phrase, words joined by \\s+, then 8/6/5/4-word
prefixes); each hit is mapped onto the NEW prose through a word-level diff. A
hit whose words are unchanged keeps its entry; a hit an edit touched gets the
same number of words read from the new prose at the mapped start. Only the
`at` line of a changed entry is rewritten, in the file's own quoting style.
An entry with several hits of which only some changed is reported, not edited.

usage (repo root): python3 -I update_anchors.py <old.json> <new.json> <report.json>"""
import bisect, difflib, glob, json, re, sys
from pathlib import Path
import yaml

old = json.load(open(sys.argv[1], encoding='utf-8'))
new = json.load(open(sys.argv[2], encoding='utf-8'))
slot = {k.split('|')[0]: k for k in old}
HEADER = 'generated by tools/gloss_map_to_anchors.py'


def spans(s):
    sp = []
    m0 = re.match(r'\s+', s)
    if m0:
        sp.append((0, m0.end()))
    return sp + [(m.start(), m.end()) for m in re.finditer(r'\S+\s*', s)]


class Map:
    def __init__(self, o, n):
        self.o, self.n = o, n
        self.os, self.ns = spans(o), spans(n)
        ot, nt = [o[a:b] for a, b in self.os], [n[a:b] for a, b in self.ns]
        self.ops = difflib.SequenceMatcher(None, ot, nt, autojunk=False).get_opcodes()
        self.starts = [a for a, _ in self.os]

    def tok(self, off):
        return bisect.bisect_right(self.starts, off) - 1

    def f(self, off):
        if off >= len(self.o):
            return len(self.n)
        i = self.tok(off)
        for tag, i1, i2, j1, j2 in self.ops:
            if i1 <= i < i2:
                if tag == 'equal':
                    return self.ns[j1 + (i - i1)][0] + (off - self.os[i][0])
                return self.ns[j1][0] if j1 < len(self.ns) else len(self.n)
        return len(self.n)

    def touches(self, lo, hi):
        hi = min(hi, len(self.o))
        if lo >= hi:
            return False
        a, b = self.tok(lo), self.tok(hi - 1)
        return any(tag != 'equal' and ((i1 <= b and i2 > a) or (i1 == i2 and a < i1 <= b))
                   for tag, i1, i2, j1, j2 in self.ops)


def pattern(words):
    return re.compile(r'\s+'.join(re.escape(w) for w in words))


def hits(chs, phrase):
    """(chapter, start, end, nwords) for the full phrase, else the first prefix
    length that matches anywhere, as _find_phrase would fall back."""
    words = phrase.split()
    for k in (None, 8, 6, 5, 4):
        part = words if k is None else words[:k]
        if k is not None and len(words) <= k:
            continue
        pat = pattern(part)
        out = [(ch, m.start(), m.end(), len(part)) for ch, t in chs.items() for m in pat.finditer(t)]
        if out:
            return out
    return []


def dump_like(old_line, phrase):
    """Rewrite one `at` line keeping its key style and indentation."""
    m = re.match(r'^(\s*(?:-\s*)?(?:"at"|at)\s*:\s*)(.*?)(,?)\s*$', old_line)
    assert m, old_line
    return f'{m.group(1)}{json.dumps(phrase, ensure_ascii=False)}{m.group(3)}\n'


report = {'changed': [], 'ambiguous': [], 'unresolved_before': [], 'files': {}}
for f in sorted(glob.glob('sources/*/anchors.yaml')):
    d = f.split('/')[1]
    raw = open(f, encoding='utf-8').read()
    first = raw.splitlines()[0] if raw else ''
    if HEADER in first:
        continue
    if d not in slot:
        continue
    oc, nc = old[slot[d]], new[slot[d]]
    changed_ch = {ch for ch in oc if oc[ch] != nc.get(ch)}
    if not changed_ch:
        continue
    entries = yaml.safe_load(raw) or []
    lines = raw.splitlines(keepends=True)
    at_lines = [i for i, ln in enumerate(lines) if re.match(r'^\s*(?:-\s*)?(?:"at"|at)\s*:', ln)]
    assert len(at_lines) == len(entries), (f, len(at_lines), len(entries))
    maps = {}
    n_changed = 0
    for e, li in zip(entries, at_lines):
        phrase = str(e['at']).strip()
        hs = hits(oc, phrase)
        if not hs:
            report['unresolved_before'].append(f"{d} {e['bekker']} {phrase[:50]!r}")
            continue
        touched = []
        for ch, s, t, nw in hs:
            if ch not in changed_ch:
                continue
            mp = maps.setdefault(ch, Map(oc[ch], nc[ch]))
            if mp.touches(s, t):
                touched.append((ch, s, nw, mp))
        if not touched:
            continue
        if len(hs) > 1:
            report['ambiguous'].append(f"{d} {e['bekker']} {phrase[:60]!r} hits={len(hs)} touched={len(touched)}")
            continue
        ch, s, nw, mp = touched[0]
        ns = mp.f(s)
        words = phrase.split()
        rest = nc[ch][ns:].split()
        new_phrase = ' '.join(rest[:len(words)])
        if not new_phrase or new_phrase == phrase:
            continue
        lines[li] = dump_like(lines[li], new_phrase)
        report['changed'].append(f"{d} {e['bekker']}: {phrase!r} -> {new_phrase!r}")
        n_changed += 1
    if n_changed:
        out = ''.join(lines)
        assert len(yaml.safe_load(out)) == len(entries)
        open(f, 'w', encoding='utf-8').write(out)
    report['files'][f] = n_changed
json.dump(report, open(sys.argv[3], 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
print({k: len(v) for k, v in report.items()})
print('per file:', {k.split('/')[1]: v for k, v in report['files'].items() if v})
