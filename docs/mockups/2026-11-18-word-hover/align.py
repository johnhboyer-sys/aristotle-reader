    import json, re, sys
    j = json.load(open(sys.argv[1]))
    seg = j["segments"][0]
    eng = seg["english"]["text"][:1551].rstrip()
    words = list(re.finditer(r"[A-Za-z’'-]+", eng))
    lines = []
    for l in seg["greek"][:18]:
        toks = [[t["t"], t["o"]] for t in l["tokens"]]
        text = l["text"]
        if l["n"] == 18:                      # chapter 2 opens at token 4
            toks = toks[:4]
            text = text[:toks[3][1] + len(toks[3][0]) + 1]
        lines.append({"n": l["n"], "text": text, "toks": toks})
    # sanity: every key names a real token, every index a real word
    for k, v in A.items():
        ln, ti = map(int, k.split("."))
        assert ti < len(lines[ln - 1]["toks"]), k
        assert all(0 <= i < len(words) for i in v), k
    used = {i for v in A.values() for i in v}
    print("greek tokens", sum(len(l["toks"]) for l in lines), "mapped", len(A),
          "| english words", len(words), "mapped", len(used), file=sys.stderr)
    print(json.dumps({"greek": lines, "english": eng, "align": A}, ensure_ascii=False))
