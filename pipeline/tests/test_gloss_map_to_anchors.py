"""gloss_map_to_anchors reads the translation the map was built on: the slot
whose id is the map's vid, parsed with that slot's options. Meta's Ross strips
the archive's repeated quotation marks (strip_quote_repeats), and its map's
offsets were moved onto that text; parsed without it every chapter is a few
characters long and the build aborts."""
import json
import pytest
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))

import gloss_map_to_anchors as g  # noqa: E402
from aristotle_pipeline.config import SOURCES_DIR, Manifest  # noqa: E402
from aristotle_pipeline.stage1_ross import parse_translation  # noqa: E402


def test_meta_anchors_are_phrases_of_the_stripped_text():
    entries = g.build("Meta", "ross")
    sec = Manifest.for_work("Meta").data["english"]["secondary"]
    prose = parse_translation(SOURCES_DIR / sec["dir"], sec["books"], sec["marker"],
                              strip_quote_repeats=True)
    flat = " ".join(" ".join(t.split()) for t in prose.values())
    gmap = json.loads((SOURCES_DIR.parent / "alignment-results/ross/Meta_ross_gloss_map.json").read_text())
    real = {a["citation"] for e in gmap.values() for a in e["anchors"] if a["tier"] in g.REAL_TIERS}
    assert len(entries) == len(real)
    assert all(e["at"] in flat for e in entries)


def test_the_slot_is_the_one_named_by_the_vid():
    # Codex: Meta has only a secondary, so "primary or secondary" also passed the
    # test above. Int has three dir-backed slots; each vid must find its own.
    assert g._slot("Int", "edghill")["dir"] == "int-edghill"
    assert g._slot("Int", "taylor")["dir"] == "int-taylor"
    assert g._slot("Int", "ackrill")["dir"] == "int-ackrill"


# ---- the overwrite guard: hand edits (John's Poetics pins) must not be lost --
ENTRIES = [{"bekker": "1447a10", "at": "Our subject being Poetry"},
           {"bekker": "1447a15", "at": "Epic poetry and Tragedy"}]


def test_a_generated_file_carries_a_header_and_may_be_regenerated(tmp_path):
    out = tmp_path / "anchors.yaml"
    g.write(out, ENTRIES, "map.json")
    assert out.read_text().startswith("# generated by tools/gloss_map_to_anchors.py")
    g.write(out, ENTRIES[:1], "map.json")          # unedited: replaced freely
    assert "1447a15" not in out.read_text()


def test_a_hand_edited_file_is_never_overwritten_without_force(tmp_path):
    out = tmp_path / "anchors.yaml"
    g.write(out, ENTRIES, "map.json")
    edited = out.read_text().replace("Epic poetry and Tragedy", "Tragedy, too")
    out.write_text(edited)
    with pytest.raises(SystemExit, match="1447a15"):
        g.write(out, ENTRIES, "map.json")
    assert out.read_text() == edited
    g.write(out, ENTRIES, "map.json", force=True)
    assert "Epic poetry" in out.read_text()


def test_an_unmarked_file_is_kept_unless_the_map_writes_the_same(tmp_path):
    out = tmp_path / "anchors.yaml"
    legacy = '- bekker: "1447a10"\n  at: "Our subject being Poetry"\n'
    out.write_text(legacy)
    g.write(out, ENTRIES[:1], "map.json")          # same content: fine, now marked
    assert out.read_text().startswith("# generated")
    out.write_text(legacy.replace("Our subject", "My subject"))
    with pytest.raises(SystemExit, match="1447a10"):
        g.write(out, ENTRIES[:1], "map.json")



def test_a_phrase_repeated_in_its_chapter_is_extended_until_unique():
    # Grok: the reader takes the first copy of a phrase in its column, so a
    # repeated `at` put the tick on the wrong copy (4 of 12,598 shipped anchors).
    rep = "and so the argument returns to the same point once more, as was said before, "
    text = "Opening words. " + rep + "first ending. " + rep + "second ending."
    at = g._phrase(text, text.rindex("and so the"))
    assert " ".join(text.split()).count(at) == 1 and "second ending" in at


def test_the_refusal_points_to_rulings(tmp_path):
    out = tmp_path / "anchors.yaml"
    out.write_text('- bekker: "1447a10"\n  at: "My subject"\n')
    with pytest.raises(SystemExit, match="rulings"):
        g.write(out, ENTRIES[:1], "map.json")
